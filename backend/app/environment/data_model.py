_KEYWORDS = (
    ("commerce", re.compile(r"shop|store|cart|checkout|catalog|commerce|payment|billing|invoice", re.I)),
    ("helpdesk", re.compile(r"helpdesk|ticket|support|service-?desk|itsm|zammad|osticket", re.I)),
    ("content", re.compile(r"blog|wiki|cms|content|docs|ghost|wordpress|news|magazine", re.I)),
)


def keyword_domain(profile: SanitizedProfile) -> str:
    hay = " ".join([profile.source] + [f"{s.name} {s.image}" for s in profile.services] +
                   [v for s in profile.services for v in s.labels.values()])
    for domain, pattern in _KEYWORDS:
        if pattern.search(hay):
            return domain
    return "generic"


MODEL_SCHEMA = {
    "type": "object",
    "required": ["tables"],
    "properties": {
        "domain": {"type": "string"},
        "tables": {
            "type": "array", "maxItems": MAX_TABLES,
            "items": {
                "type": "object", "required": ["name", "columns"],
                "properties": {
                    "name": {"type": "string"},
                    "columns": {"type": "array", "maxItems": MAX_COLUMNS, "items": {
                        "type": "object", "required": ["name", "type"],
                        "properties": {"name": {"type": "string"}, "type": {"type": "string", "enum": COLUMN_TYPES},
                                       "ref": {"type": ["string", "null"]}}}},
                },
            },
        },
    },
}
MODEL_POLICY = (
    "Design a small, plausible, entirely fictional relational schema for the database of the described "
    "application, judging only from the service names, images and roles given. 2 to 6 tables, each with an "
    "'id' first column of type id. Column types come only from the allowed list; use 'ref' with a target "
    "table for foreign keys. Use lowercase snake_case names and avoid SQL reserved words. Never include real "
    "names, secrets or data; only the structure."
)


def pick_model(profile: SanitizedProfile, provider: AIProvider | None) -> tuple[DataModel, dict]:
    """AI proposal if a model is available and its answer validates; otherwise the keyword default."""
    info: dict = {}
    if provider is not None and getattr(provider, "is_model", False):
        context = {
            "task": "data_model", "project": profile.source, "allowed_column_types": COLUMN_TYPES,
            "services": [{"name": s.name, "role": s.role, "image": s.image} for s in profile.services],
        }
        try:
            raw = provider.generate_structured(system_policy=MODEL_POLICY, context=context, output_schema=MODEL_SCHEMA)
            model = DataModel.model_validate({**raw, "domain": "custom"})
            return model, {"source": f"ai:{provider.name}", "domain": "custom", "tables": [t.name for t in model.tables]}
        except (ValidationError, ValueError, TypeError, KeyError) as exc:
            info["ai_rejected"] = type(exc).__name__
        except Exception as exc:  # noqa: BLE001  (provider outage etc.: never fatal)
            info["ai_error"] = type(exc).__name__
    domain = keyword_domain(profile)
    model = DOMAIN_MODELS[domain]
    return model, {"source": f"keyword:{domain}", "domain": domain, "tables": [t.name for t in model.tables], **info}


# ---- rows and SQL ---------------------------------------------------------------------------------
_PHRASES = [
    "Quarterly review", "Access request", "Password reset", "Invoice question", "Onboarding checklist",
    "Maintenance window", "Export failed", "Renewal reminder", "Welcome message", "Policy update",
    "Capacity planning", "Backup verification",
]
_STATUS = ["active", "pending", "closed", "archived"]


def generate_rows(model: DataModel, synth: Synth, people: list[Person]) -> dict[str, list[dict]]:
    rows: dict[str, list[dict]] = {}
    for name in model.generation_order():
        table = next(t for t in model.tables if t.name == name)
        personal = any(c.type in ("email", "name") for c in table.columns)
        count = len(people) if personal else 8
        out = []
        for i in range(count):
            row: dict = {}
            for c in table.columns:
                if c.type == "id":
                    row[c.name] = i + 1
                elif c.type == "int":
                    row[c.name] = synth.rng.randint(1, 20)
                elif c.type == "email":
                    row[c.name] = people[i % len(people)].email
                elif c.type == "name":
                    row[c.name] = people[i % len(people)].full_name
                elif c.type == "text":
                    row[c.name] = synth.rng.choice(_PHRASES)
                elif c.type == "status":
                    row[c.name] = synth.rng.choice(_STATUS)
                elif c.type == "amount":
                    row[c.name] = synth.rng.randint(500, 50_000)
                elif c.type == "timestamp":
                    row[c.name] = synth.ts(60 * (count - i)).strftime("%Y-%m-%d %H:%M:%S")
                elif c.type == "code":
                    row[c.name] = f"{table.name[:3].upper()}-{1000 + i}"
                elif c.type == "bool":
                    row[c.name] = synth.rng.choice([0, 1])
                elif c.type == "ref" and c.ref is not None:  # the model validator guarantees a target
                    row[c.name] = synth.rng.choice(rows[c.ref])["id"]
            out.append(row)
        rows[name] = out
    return {t.name: rows[t.name] for t in model.tables}  # keep the model's table order


_SQL = {
    "postgres": {"id": "SERIAL PRIMARY KEY", "int": "INT", "email": "TEXT", "name": "TEXT", "text": "TEXT",
                 "status": "TEXT", "amount": "INT", "timestamp": "TIMESTAMP", "code": "TEXT", "bool": "BOOLEAN"},
    "mysql": {"id": "INT AUTO_INCREMENT PRIMARY KEY", "int": "INT", "email": "VARCHAR(255)", "name": "VARCHAR(255)",
              "text": "VARCHAR(255)", "status": "VARCHAR(32)", "amount": "INT", "timestamp": "DATETIME",
              "code": "VARCHAR(64)", "bool": "TINYINT(1)"},
}


def schema_sql(model: DataModel, engine: str) -> str:
    types, lines = _SQL[engine], []
    for name in model.generation_order():
        t = next(t for t in model.tables if t.name == name)
        cols = [f"{c.name} INT REFERENCES {c.ref}(id)" if c.type == "ref" else f"{c.name} {types[c.type]}"
                for c in t.columns]
        lines.append(f"CREATE TABLE {t.name} ({', '.join(cols)});")
    return "\n".join(lines) + "\n"


def _lit(v) -> str:
    return str(v) if isinstance(v, int) else "'" + str(v).replace("'", "''") + "'"


def inserts_sql(model: DataModel, rows: dict[str, list[dict]], engine: str) -> str:
    bool_cols = {(t.name, c.name) for t in model.tables for c in t.columns if c.type == "bool"}
    out = []
    for name in model.generation_order():
        for r in rows[name]:
            vals = []
            for col, v in r.items():
                vals.append(("TRUE" if v else "FALSE") if engine == "postgres" and (name, col) in bool_cols else _lit(v))
            out.append(f"INSERT INTO {name} ({', '.join(r)}) VALUES ({', '.join(vals)});")
    return "\n".join(out)
